use zenoh_proto::{
    SessionError,
    exts::Attachment,
    fields::{Encoding, Timestamp},
    keyexpr,
};

use crate::{
    api::session::{Session, put::PutBuilder},
    config::ZSessionConfig,
};

/// Reusable borrowed-key settings for publications.
///
/// The current implementation creates no protocol Interest declaration or callback
/// registration for this handle. Dropping it only drops local settings; `undeclare`
/// is a consuming no-op. Each operation created from it has its own lifecycle.
pub struct Publisher<'a, 'transport, 'resources: 'transport, Config>
where
    Config: ZSessionConfig,
{
    session: &'a Session<'transport, 'resources, Config>,

    ke: &'a keyexpr,

    encoding: Encoding<'a>,
    timestamp: Option<Timestamp>,
    attachment: Option<Attachment<'a>>,
}

impl<'a, 'transport, 'resources: 'transport, Config> Publisher<'a, 'transport, 'resources, Config>
where
    Config: ZSessionConfig,
{
    /// Create a publication using these settings and the borrowed payload.
    ///
    /// This sends nothing until [`PutBuilder::finish`] is awaited. The resulting
    /// builder borrows the session, key and metadata, independently of this handle.
    pub fn put(&self, payload: &'a [u8]) -> PutBuilder<'a, 'transport, 'resources, Config> {
        PutBuilder {
            session: self.session,
            ke: self.ke,
            payload,
            encoding: self.encoding.clone(),
            timestamp: self.timestamp,
            attachment: self.attachment.clone(),
        }
    }

    /// Consume the handle; currently sends no Interest or undeclaration message.
    pub async fn undeclare(self) -> core::result::Result<(), SessionError> {
        // No interest is sent by the current publisher implementation.
        Ok(())
    }

    /// Borrow the key expression selected for this handle.
    pub fn keyexpr(&self) -> &keyexpr {
        self.ke
    }
}

/// Configure reusable publication settings without sending a protocol declaration.
///
/// Call [`Self::finish`] to obtain a local [`Publisher`]; actual sends use
/// [`Publisher::put`] followed by [`PutBuilder::finish`].
pub struct PublisherBuilder<'a, 'transport, 'resources: 'transport, Config>
where
    Config: ZSessionConfig,
{
    session: &'a Session<'transport, 'resources, Config>,

    ke: &'a keyexpr,
    encoding: Encoding<'a>,
    timestamp: Option<Timestamp>,
    attachment: Option<Attachment<'a>>,
}

impl<'a, 'transport, 'resources: 'transport, Config>
    PublisherBuilder<'a, 'transport, 'resources, Config>
where
    Config: ZSessionConfig,
{
    pub(crate) fn new(
        session: &'a Session<'transport, 'resources, Config>,
        ke: &'a keyexpr,
    ) -> Self {
        Self {
            session,
            ke,
            encoding: Encoding::default(),
            timestamp: None,
            attachment: None,
        }
    }

    /// Replace the borrowed key expression used by this builder.
    pub fn keyexpr(mut self, ke: &'a keyexpr) -> Self {
        self.ke = ke;
        self
    }

    /// Set the payload encoding metadata; this does not transform the payload.
    ///
    /// The default is [`Encoding::default`]. Any schema bytes are borrowed through sending.
    pub fn encoding(mut self, encoding: Encoding<'a>) -> Self {
        self.encoding = encoding;
        self
    }

    /// Attach an application-supplied timestamp; no timestamp is generated by default.
    pub fn timestamp(mut self, timestamp: Timestamp) -> Self {
        self.timestamp = Some(timestamp);
        self
    }

    /// Attach opaque metadata borrowed through sending; absent by default.
    pub fn attachment(mut self, attachment: &'a [u8]) -> Self {
        self.attachment = Some(Attachment { buffer: attachment });
        self
    }

    /// Return reusable local settings; currently sends no Interest or other declaration.
    ///
    /// The result is always `Ok` in this implementation; the fallible signature does
    /// not imply a router handshake or acknowledgment.
    pub async fn finish(
        self,
    ) -> core::result::Result<Publisher<'a, 'transport, 'resources, Config>, SessionError> {
        // TODO: send interest msg
        Ok(Publisher {
            session: self.session,
            ke: self.ke,
            encoding: self.encoding,
            timestamp: self.timestamp,
            attachment: self.attachment,
        })
    }
}

impl<'transport, 'resources: 'transport, Config> Session<'transport, 'resources, Config>
where
    Config: ZSessionConfig,
{
    /// Configure reusable publication defaults for a borrowed key.
    ///
    /// Call [`PublisherBuilder::finish`] to obtain the handle. This API currently
    /// creates local settings only; use [`Publisher::put`] to publish.
    pub fn declare_publisher<'a>(
        &'a self,
        ke: &'a keyexpr,
    ) -> PublisherBuilder<'a, 'transport, 'resources, Config> {
        PublisherBuilder::new(self, ke)
    }
}
