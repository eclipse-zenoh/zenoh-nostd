use zenoh_proto::{exts::*, fields::*, msgs::*, *};

use crate::{api::session::Session, config::ZSessionConfig, io::transport::ZTransportLinkTx};

/// Borrowed publication data, sent only when [`Self::finish`] is awaited.
///
/// Key, payload and optional metadata must remain valid through the send. Creating
/// or dropping an unpolled builder sends nothing.
pub struct PutBuilder<'a, 'transport, 'resources: 'transport, Config>
where
    Config: ZSessionConfig,
{
    pub(crate) session: &'a Session<'transport, 'resources, Config>,

    pub(crate) ke: &'a keyexpr,
    pub(crate) payload: &'a [u8],

    pub(crate) encoding: Encoding<'a>,
    pub(crate) timestamp: Option<Timestamp>,
    pub(crate) attachment: Option<Attachment<'a>>,
}

impl<'a, 'transport, 'resources: 'transport, Config> PutBuilder<'a, 'transport, 'resources, Config>
where
    Config: ZSessionConfig,
{
    pub(crate) fn new(
        session: &'a Session<'transport, 'resources, Config>,
        ke: &'a keyexpr,
        payload: &'a [u8],
    ) -> Self {
        Self {
            session,
            ke,
            payload,
            encoding: Encoding::default(),
            timestamp: None,
            attachment: None,
        }
    }

    /// Set the borrowed payload bytes; the application retains ownership through sending.
    pub fn payload(mut self, payload: &'a [u8]) -> Self {
        self.payload = payload;
        self
    }

    /// Set the payload encoding metadata; this does not transform the payload.
    ///
    /// The default is [`Encoding::default`]. Any schema text is borrowed through sending.
    pub fn encoding(mut self, encoding: Encoding<'a>) -> Self {
        self.encoding = encoding;
        self
    }

    /// Attach an application-supplied timestamp; no timestamp is generated by default.
    pub fn timestamp(mut self, timestamp: Timestamp) -> Self {
        self.timestamp = Some(timestamp);
        self
    }

    /// Attach opaque metadata borrowed through sending; absent by default.
    pub fn attachment(mut self, attachment: &'a [u8]) -> Self {
        self.attachment = Some(Attachment { buffer: attachment });
        self
    }

    /// Write the publication to the transport.
    ///
    /// Success is not a remote delivery acknowledgment and may leave adapter-owned
    /// buffers pending; use [`Session::flush`] for normal finite completion.
    /// If sending is cancelled or fails, discard the whole connection.
    ///
    /// # Buffer limits
    ///
    /// Ensure the whole encoded publication fits the configured protocol batch,
    /// including key, metadata and framing. The current codec can skip an
    /// oversized message without returning an error; no fragmentation is provided.
    pub async fn finish(self) -> core::result::Result<(), SessionError> {
        let msg = Push {
            wire_expr: WireExpr::from(self.ke),
            payload: PushBody::Put(Put {
                payload: self.payload,
                encoding: self.encoding,
                timestamp: self.timestamp,
                attachment: self.attachment,
                ..Default::default()
            }),
            timestamp: self.timestamp,
            ..Default::default()
        };

        Ok(self
            .session
            .driver
            .tx()
            .await
            .send(core::iter::once(NetworkMessage {
                reliability: Reliability::default(),
                qos: QoS::default(),
                body: NetworkBody::Push(msg),
            }))
            .await?)
    }
}

impl<'transport, 'resources: 'transport, Config> Session<'transport, 'resources, Config>
where
    Config: ZSessionConfig,
{
    /// Build a publication borrowing `ke` and `payload`; await [`PutBuilder::finish`] to send it.
    ///
    /// Keep [`Session::run`] polled concurrently. Sending does not retain data for
    /// future gets; a queryable or storage must serve those requests.
    pub fn put<'a>(
        &'a self,
        ke: &'a keyexpr,
        payload: &'a [u8],
    ) -> PutBuilder<'a, 'transport, 'resources, Config> {
        PutBuilder::new(self, ke, payload)
    }
}
